const useI18nStore = create<any>((set: any, get: any) => ({
  lang: 'tr',
  setLang: (lang: SupportedLang) => set({ lang }),
  t: (key: string) => {
    const currentLang = get().lang as SupportedLang
    return translations[currentLang]?.[key] || translations['tr']?.[key] || key
  }
}))


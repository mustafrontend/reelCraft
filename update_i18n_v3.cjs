for (const lang in dict) {
  const keysStr = Object.entries(dict[lang])
    .map(([k, v]) => `    '${k}': '${v.replace(/'/g, "\\'")}',`)
    .join('\n')
  
  const regex = new RegExp(`(${lang}:\\s*{[\\s\\S]*?)(},|}\\n})`, 'm')
  content = content.replace(regex, `$1\n${keysStr}\n$2`)
}

fs.writeFileSync(path, content, 'utf8')
